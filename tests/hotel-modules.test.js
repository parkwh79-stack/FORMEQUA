function furnish(rooms){
  const plan={level:2,use:"hotel",status:"generated",rooms:structuredClone(rooms),doors:[],walls:[],furniture:[],metrics:{},warnings:[]};
  for(const r of plan.rooms){
    const x=r.minX,depth=r.maxZ-r.minZ;
    plan.doors.push({x:x+2.5,z:depth,width:.95,axis:"x",roomId:r.id});
    if(r.type==="hotel_service")continue;
    const bath={minX:x,maxX:x+2.3,minZ:0,maxZ:2.4},door={x:x+1.15,z:2.4,width:.9,axis:"x",kind:"ensuite",roomId:r.id};
    r.ensuite={bounds:bath,door};plan.doors.push(door);
    const add=(type,x,z,width,depth,zone)=>plan.furniture.push({type,x,z,width,depth,roomId:r.id,...(zone?{zone}:{})});
    add("bed",x+1.2,4.2,.9,2);if(r.type==="guest_twin")add("bed",x+3.2,4.2,.9,2);
    if(r.type==="guest_suite")add("sofa",x+2.5,6.3,1.5,.8);
    add("toilet",x+.5,.5,.65,.75,"ensuite");add("vanity",x+1.6,1.2,.9,.5,"ensuite");
  }
  return plan;
}
